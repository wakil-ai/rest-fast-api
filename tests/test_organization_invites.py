async def test_losing_the_claim_race_returns_410_and_creates_no_membership():
    """The conditional invite claim IS the single-use gate.

    If the claim update matches no pending row — another request won the race — the
    accept must abort before any membership row is written. Simulated by forcing
    update_documents to report zero modified rows.
    """
    org_svc = _make_org_service()
    org = await org_svc.create_organization(user_id="u1", name="Legal Dept")
    svc = _make_member_service(org_svc)
    invite = await svc.create_invite(org["_id"], "u1")
    svc.db.update_documents = AsyncMock(return_value=0)

    with pytest.raises(HTTPException) as exc:
        await svc.accept_invite(invite["_id"], "u2")
    assert exc.value.status_code == 410

    members = svc.db.docs[settings.ORGANIZATION_MEMBERS_COLLECTION]
    assert [m["user_id"] for m in members] == ["u1"]


async def test_removed_member_rejoining_reactivates_their_row():
    """(org_id, user_id) is uniquely indexed, so a removed member still owns that key.

    Re-joining must reactivate the existing row, not insert a second one — a blind
    insert would raise DuplicateKeyError against the real index.
    """
    org_svc = _make_org_service()
    org = await org_svc.create_organization(user_id="u1", name="Legal Dept")
    svc = _make_member_service(org_svc)
    org_svc.db.docs[settings.ORGANIZATION_MEMBERS_COLLECTION].append(
        {
            "_id": "omem-old",
            "org_id": org["_id"],
            "user_id": "u2",
            "role": "member",
            "status": "removed",
            "joined_at": datetime.now(timezone.utc),
        }
    )
    invite = await svc.create_invite(org["_id"], "u1")

    result = await svc.accept_invite(invite["_id"], "u2")

    assert result["membership_role"] == "member"
    rows = [
        m
        for m in svc.db.docs[settings.ORGANIZATION_MEMBERS_COLLECTION]
        if m["user_id"] == "u2"
    ]
    assert len(rows) == 1
    assert rows[0]["_id"] == "omem-old"
    assert rows[0]["status"] == "active"


