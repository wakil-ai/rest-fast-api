"""Tests for organization one-time invite links.

A link is generated by an admin and shared. The first user to accept it burns it:
every later acceptance attempt returns 410.
"""

from datetime import datetime, timedelta, timezone
from unittest.mock import AsyncMock, MagicMock

import pytest
from fastapi import HTTPException

from core.config import settings
from tests.test_organization_service import _make_org_service


def _make_member_service(org_svc):
    from services.organization_member_service import OrganizationMemberService

    svc = OrganizationMemberService.__new__(OrganizationMemberService)
    svc.db = org_svc.db
    svc.history = MagicMock()
    svc.history.get_user = AsyncMock(return_value={"_id": "u2", "first_name": "Bob"})
    svc.orgs = org_svc
    svc.members_collection = settings.ORGANIZATION_MEMBERS_COLLECTION
    svc.invites_collection = settings.ORGANIZATION_INVITES_COLLECTION
    svc.invite_prefix = "oinv-"
    svc.member_prefix = "omem-"
    return svc


async def test_admin_creates_invite_with_join_path():
    org_svc = _make_org_service()
    org = await org_svc.create_organization(user_id="u1", name="Legal Dept")
    svc = _make_member_service(org_svc)

    invite = await svc.create_invite(org["_id"], "u1")

    assert invite["_id"].startswith("oinv-")
    assert invite["org_id"] == org["_id"]
    assert invite["created_by"] == "u1"
    assert invite["status"] == "pending"
    assert invite["accepted_by"] is None
    assert invite["join_path"] == f"organizations/join/{invite['_id']}"
    assert invite["expires_at"] > datetime.now(timezone.utc)


async def test_non_admin_cannot_create_invite():
    org_svc = _make_org_service()
    org = await org_svc.create_organization(user_id="u1", name="Legal Dept")
