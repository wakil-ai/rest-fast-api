async def test_accept_invite_creates_member_and_burns_the_link():
    org_svc = _make_org_service()
    org = await org_svc.create_organization(user_id="u1", name="Legal Dept")
    svc = _make_member_service(org_svc)
    invite = await svc.create_invite(org["_id"], "u1")

    result = await svc.accept_invite(invite["_id"], "u2")

    assert result["org_id"] == org["_id"]
    assert result["user_id"] == "u2"
    assert result["membership_role"] == "member"

