async def test_list_members_returns_admin_first_with_profile_fields():
    org_svc = _make_org_service()
    org = await org_svc.create_organization(user_id="u1", name="Legal Dept")
    svc = _make_member_service(org_svc)
    profiles = {
        "u1": {"_id": "u1", "first_name": "Ada", "last_name": "L", "username": "ada"},
        "u2": {"_id": "u2", "first_name": "Bob", "last_name": "M", "username": "bob"},
    }
    svc.history.get_user = AsyncMock(side_effect=lambda uid: profiles.get(uid))
    invite = await svc.create_invite(org["_id"], "u1")
    await svc.accept_invite(invite["_id"], "u2")

    members = await svc.list_members(org["_id"], "u1")

    assert [m["user_id"] for m in members] == ["u1", "u2"]
    assert members[0]["role"] == "admin"
    assert members[0]["first_name"] == "Ada"
    assert members[1]["role"] == "member"
    assert members[1]["username"] == "bob"


