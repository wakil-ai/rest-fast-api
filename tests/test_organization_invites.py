    assert stored_invite["status"] == "accepted"
    assert stored_invite["accepted_by"] == "u2"
    assert stored_invite["accepted_at"] is not None

    members = svc.db.docs[settings.ORGANIZATION_MEMBERS_COLLECTION]
    assert [m["user_id"] for m in members] == ["u1", "u2"]
    assert members[1]["role"] == "member"
    assert members[1]["status"] == "active"
    assert "invited_by" not in members[1]


